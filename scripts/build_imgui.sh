#!/usr/bin/env bash
# Builds Dear ImGui (docking branch) + the SDL3 / SDL_GPU backends as a static
# library, and vendors the Odin bindings from Capati/odin-imgui.
#
# Replaces the premake step of odin-imgui with a plain shell script so the
# only requirements are: git, python3 (with venv), a C++ compiler, SDL3 headers.
#
# Output: third_party/odin-imgui/{imgui.odin, backends/, libimgui_linux_<arch>.a}
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/third_party/odin-imgui"
WORK="$ROOT/build/deps"

BINDINGS_REPO="https://github.com/Capati/odin-imgui"
BINDINGS_REV="5402a803e04966bbaf1c3a4632ed44e1a59f9af8"
IMGUI_VERSION="v1.92.9b-docking"
DEAR_BINDINGS_VERSION="DearBindings_v0.21_ImGui_v1.92.9b-docking"

CXX="${CXX:-c++}"
ARCH="$(uname -m)"          # x86_64 / aarch64
[ "$ARCH" = "aarch64" ] && ARCH="arm64"

mkdir -p "$WORK"

clone() { # url dir rev
	if [ ! -d "$2/.git" ]; then
		git clone --quiet "$1" "$2"
	fi
	git -C "$2" fetch --quiet --tags origin
	git -C "$2" checkout --quiet "$3"
}

echo "==> Fetching sources"
clone "$BINDINGS_REPO"                           "$WORK/odin-imgui"    "$BINDINGS_REV"
clone https://github.com/ocornut/imgui           "$WORK/imgui"         "$IMGUI_VERSION"
clone https://github.com/dearimgui/dear_bindings "$WORK/dear_bindings" "$DEAR_BINDINGS_VERSION"

echo "==> Generating C API (dear_bindings)"
if [ ! -x "$WORK/venv/bin/python" ]; then
	python3 -m venv "$WORK/venv"
	"$WORK/venv/bin/pip" install --quiet -r "$WORK/dear_bindings/requirements.txt"
fi
mkdir -p "$WORK/generated"
"$WORK/venv/bin/python" "$WORK/dear_bindings/dear_bindings.py" \
	--nogeneratedefaultargfunctions \
	-o "$WORK/generated/dcimgui" "$WORK/imgui/imgui.h"

echo "==> Compiling ImGui + SDL3/SDL_GPU backends"
OBJ="$WORK/obj"; rm -rf "$OBJ"; mkdir -p "$OBJ"
SDL_CFLAGS="$(pkg-config --cflags sdl3 2>/dev/null || echo -I/usr/include)"
SOURCES=(
	"$WORK"/imgui/imgui.cpp
	"$WORK"/imgui/imgui_demo.cpp
	"$WORK"/imgui/imgui_draw.cpp
	"$WORK"/imgui/imgui_tables.cpp
	"$WORK"/imgui/imgui_widgets.cpp
	"$WORK"/generated/dcimgui.cpp
	"$WORK"/imgui/backends/imgui_impl_sdl3.cpp
	"$WORK"/imgui/backends/imgui_impl_sdlgpu3.cpp
)
for src in "${SOURCES[@]}"; do
	"$CXX" -c -O2 -std=c++11 -fPIC -fno-exceptions -fno-rtti -fno-threadsafe-statics \
		-DIMGUI_DISABLE_OBSOLETE_FUNCTIONS -DIMGUI_DISABLE_OBSOLETE_KEYIO \
		'-DIMGUI_IMPL_API=extern "C"' -DNDEBUG \
		-I"$WORK/imgui" -I"$WORK/imgui/backends" -I"$WORK/generated" $SDL_CFLAGS \
		"$src" -o "$OBJ/$(basename "$src" .cpp).o" &
done
wait

echo "==> Vendoring bindings into third_party/odin-imgui"
rm -rf "$OUT"; mkdir -p "$OUT/backends"
cp "$WORK/odin-imgui/imgui.odin" "$WORK/odin-imgui/LICENSE" "$OUT/"
cp -r "$WORK/odin-imgui/backends/sdl3" "$WORK/odin-imgui/backends/sdlgpu3" "$OUT/backends/"
cat > "$OUT/impl_enabled.odin" <<'EOF'
package imgui

// Generated by scripts/build_imgui.sh: backends compiled into the library.
BACKEND_SDL3_ENABLED    :: true
BACKEND_SDLGPU3_ENABLED :: true
EOF
ar rcs "$OUT/libimgui_linux_${ARCH}.a" "$OBJ"/*.o
echo "==> Done: $OUT/libimgui_linux_${ARCH}.a"
